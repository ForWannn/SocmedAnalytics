-- Jalankan sekali di Supabase Dashboard > SQL Editor > New query
create table if not exists public.follower_snapshots (
  id bigint generated by default as identity primary key,
  instagram_user_id text not null,
  username text,
  snapshot_date date not null,
  followers_count bigint not null check (followers_count >= 0),
  created_at timestamptz not null default now(),
  constraint follower_snapshots_account_day_unique unique (instagram_user_id, snapshot_date)
);

create index if not exists follower_snapshots_account_date_idx
  on public.follower_snapshots (instagram_user_id, snapshot_date desc);

-- API memakai service role di server; akses browser anonim tidak diizinkan.
alter table public.follower_snapshots enable row level security;
